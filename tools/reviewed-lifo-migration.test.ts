import { describe, expect, it } from 'vitest';
import baseline from './fixtures/reviewed-lifo-baseline.json' with { type: 'json' };
import { reviewedLifoMigrationCases, runReviewedLifoMigration } from './fixtures/reviewed-lifo-migration.js';
import { loadRuntimeCatalog } from './runtime-catalog.js';
import { prepareCounterLifoSchedule } from '../packages/engine/src/counter-lifo-schedule.js';
import { setupBoundedCounterCandidate } from './fixtures/bounded-counter-candidate.js';
import { setupTrapThreeSevenBoard } from './fixtures/trap-three-seven-candidate.js';
import { applyAction } from '../packages/engine/src/duel.js';
import type { EngineAction } from '../packages/engine/src/actions.js';
import type { DuelState } from '../packages/protocol/src/duel.js';
const { registry } = loadRuntimeCatalog();
const cases = reviewedLifoMigrationCases(registry);

describe('shared LIFO migration preserves the live v5 contract', () => {
  it('uses the pre-edit baseline from 88b1618, not a fixture regenerated by this test', () => {
    expect(baseline.source).toBe('88b16180cab1ca5e4b2e1eb1d721ccd467168c0c');
    expect(cases.map(c => c.key)).toEqual(baseline.cases.map(c => c.key)); expect(cases).toHaveLength(142);
  });
  it.each(cases)('preserves every full state and raw event hash for $key', o => {
    expect(runReviewedLifoMigration(registry, o)).toEqual(baseline.cases.find(c => c.key === o.key));
  });
  it.each(['empty', 'too-long', 'duplicate-id', 'duplicate-source', 'blank-id', 'blank-source', 'flag', 'effect-flag',
    'speed', 'first-counter', 'wrong-response', 'counter-response-missing', 'trap-after-counter', 'spell-after-root', 'trap-after-spell', 'root-response', 'missing-flag'])('rejects invalid kernel geometry %s without mutation', mode => {
    const f = setupBoundedCounterCandidate(registry, { owners: ['a', 'b', 'a'] }), links = f.state.chain;
    if (mode === 'empty') links.splice(0);
    if (mode === 'too-long') while (links.length < 9) links.push(structuredClone(links.at(-1)!));
    if (mode === 'duplicate-id') links[2]!.id = links[1]!.id; if (mode === 'duplicate-source') links[2]!.source = links[1]!.source;
    if (mode === 'blank-id') links[0]!.id = ''; if (mode === 'blank-source') links[0]!.source = '';
    if (mode === 'flag') links[0]!.activationNegated = true; if (mode === 'effect-flag') links[0]!.effectNegated = true;
    if (mode === 'speed') links[1]!.spellSpeed = 4 as never; if (mode === 'first-counter') links[0]!.spellSpeed = 3;
    if (mode === 'wrong-response') links[2]!.respondingToLinkId = links[0]!.id;
    if (mode === 'counter-response-missing') delete links[1]!.respondingToLinkId;
    if (mode === 'trap-after-counter') { links[2]!.spellSpeed = 2; delete links[2]!.respondingToLinkId; }
    if (mode === 'spell-after-root') { links[1]!.spellSpeed = 1; delete links[1]!.respondingToLinkId; }
    if (mode === 'trap-after-spell') { links[0]!.spellSpeed = 1; links[1]!.spellSpeed = 2; delete links[1]!.respondingToLinkId; }
    if (mode === 'root-response') links[0]!.respondingToLinkId = 'other';
    if (mode === 'missing-flag') delete (links[0] as any).activationNegated;
    const before = structuredClone(links); expect(() => prepareCounterLifoSchedule(links)).toThrow(); expect(links).toEqual(before);
  });
  it('returns an immutable schedule without freezing or changing the caller graph', () => {
    const f = setupBoundedCounterCandidate(registry, { owners: ['a', 'b', 'a', 'b', 'a', 'b'] }), before = structuredClone(f.state);
    const p = prepareCounterLifoSchedule(f.state.chain);
    expect(p.filter(s => s.kind === 'resolve').map(s => s.linkIndex)).toEqual([6, 4, 2, 0]);
    expect(p.filter(s => s.kind === 'skip').map(s => s.linkIndex)).toEqual([5, 3, 1]);
    expect(Object.isFrozen(p[0])).toBe(true); expect(Object.isFrozen(f.state.chain[0])).toBe(false); expect(f.state).toEqual(before);
  });
  it.each(['a', 'b'])('structural scheduling does not open the fifth live activation for %s', actor => {
    const f = setupTrapThreeSevenBoard(registry, actor, [true, false, true], 'normal', 'main1', true);
    const p = f.state.players.find(p => p.id === f.other)!, extra = p.deck.find(id => f.state.cards[id]!.definition.id === 'official:03819470')!;
    p.deck.splice(p.deck.indexOf(extra), 1); p.spellsTraps[3] = extra;
    f.state.cards[extra]!.location = { kind: 'spell-trap', playerId: p.id, slot: 3 }; f.state.cards[extra]!.position = 'face-down'; f.state.cards[extra]!.markers.setOnTurn = 1;
    let s: DuelState = f.state;
    const act = (who: string, action: EngineAction) => { const r = applyAction(registry, s, { actorId: who, expectedStateVersion: s.stateVersion, action }); expect(r.accepted).toBe(true); s = r.state; };
    act(actor, { type: 'normal-summon', instanceId: f.target, slot: 0, tributeIds: [] }); act(actor, { type: 'pass' });
    act(f.other, { type: 'activate-trap', instanceId: f.trap, targetId: f.target });
    for (const [who, source] of [[f.firstOwner, f.first], [f.secondOwner, f.second], [f.topOwner, f.top]]) {
      if (s.timing.priorityPlayer !== who) act(s.timing.priorityPlayer!, { type: 'pass' });
      act(who!, { type: 'activate-lp-counter-trap', instanceId: source!, respondingToLinkId: s.chain.at(-1)!.id });
    }
    const hypothetical = [...s.chain, { ...s.chain.at(-1)!, id: 'hypothetical-fifth', source: extra, respondingToLinkId: s.chain.at(-1)!.id }];
    expect(prepareCounterLifoSchedule(hypothetical).some(s => s.linkIndex === 4)).toBe(true);
    const before = structuredClone(s), denied = applyAction(registry, s, { actorId: f.other, expectedStateVersion: s.stateVersion,
      action: { type: 'activate-lp-counter-trap', instanceId: extra, respondingToLinkId: s.chain.at(-1)!.id } });
    expect(denied).toMatchObject({ accepted: false, code: 'illegal-timing' }); expect(denied.state).toBe(s); expect(s).toEqual(before);
  });
});
