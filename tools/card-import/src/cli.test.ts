import { cp, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { run } from './cli.js';

const repository = fileURLToPath(new URL('../../../', import.meta.url));
let root: string;
beforeEach(async () => {
  root = await mkdtemp(join(tmpdir(), 'ygo-card-import-'));
  await cp(join(repository, 'data'), join(root, 'data'), { recursive: true });
  vi.spyOn(console, 'log').mockImplementation(() => {});
});
afterEach(async () => { vi.restoreAllMocks(); vi.unstubAllGlobals(); await rm(root, { recursive: true, force: true }); });
const readOutput = () => readFile(join(root, 'data/generated/pilot.json'), 'utf8');

describe('import CLI persistence', () => {
  it('imports twice offline without modifying raw, overlays or generated bytes', async () => {
    const network = vi.fn(() => { throw new Error('No network in offline import'); });
    vi.stubGlobal('fetch', network);
    const output = await readOutput();
    const reviews = await readFile(join(root, 'data/reviews/pilot.overlays.json'), 'utf8');
    await run('import', root); await run('import', root); await run('check', root);
    expect(await readOutput()).toBe(output);
    expect(await readFile(join(root, 'data/reviews/pilot.overlays.json'), 'utf8')).toBe(reviews);
    expect(network).not.toHaveBeenCalled();
    expect((await readdir(join(root, 'data/generated'))).filter(n => n.includes('.tmp-'))).toEqual([]);
  });
  it('leaves the last valid bundle and overlays untouched after a review conflict', async () => {
    const output = await readOutput();
    const path = join(root, 'data/reviews/pilot.overlays.json');
    const overlays = JSON.parse(await readFile(path, 'utf8'));
    overlays[0].baseFingerprint = '0'.repeat(64);
    const edited = JSON.stringify(overlays);
    await writeFile(path, edited);
    await expect(run('import', root)).rejects.toThrow('Review conflict');
    expect(await readOutput()).toBe(output);
    expect(await readFile(path, 'utf8')).toBe(edited);
  });
  it('detects hand edits to generated data in check mode', async () => {
    const path = join(root, 'data/generated/pilot.json');
    const content = JSON.parse(await readFile(path, 'utf8'));
    content.cards[0].text += ' changed fixture';
    await writeFile(path, JSON.stringify(content));
    await expect(run('check', root)).rejects.toThrow('stale/edited');
  });
  it('fetch failure does not replace receipt or output', async () => {
    vi.stubGlobal('fetch', vi.fn(async () => new Response('source unavailable', { status: 503 })));
    const receiptPath = join(root, 'data/import/pilot.receipt.json');
    const receipt = await readFile(receiptPath, 'utf8'); const output = await readOutput();
    await expect(run('fetch', root)).rejects.toThrow('HTTP 503');
    expect(await readFile(receiptPath, 'utf8')).toBe(receipt);
    expect(await readOutput()).toBe(output);
  });
  it('refresh caches a single batch without fetching artwork or overwriting reviews', async () => {
    const receipt = JSON.parse(await readFile(join(root, 'data/import/pilot.receipt.json'), 'utf8'));
    const raw = await readFile(join(root, `data/raw/ygoprodeck/${receipt.sha256}.json`), 'utf8');
    const network = vi.fn(async () => new Response(raw, { status: 200 }));
    vi.stubGlobal('fetch', network);
    const reviews = await readFile(join(root, 'data/reviews/pilot.overlays.json'), 'utf8');
    await run('fetch', root); await run('import', root); await run('check', root);
    expect(network).toHaveBeenCalledTimes(1);
    expect(await readFile(join(root, 'data/reviews/pilot.overlays.json'), 'utf8')).toBe(reviews);
  });
});

describe('failed snapshot imports preserve the last usable data', () => {
  it('rejects corrupted raw input without replacing the bundle or reviews', async () => {
    const receiptPath = join(root, 'data/import/pilot.receipt.json');
    const receiptText = await readFile(receiptPath, 'utf8');
    const receipt = JSON.parse(receiptText);
    const rawPath = join(root, `data/raw/ygoprodeck/${receipt.sha256}.json`);
    const raw = await readFile(rawPath, 'utf8');
    const output = await readOutput();
    const reviews = await readFile(join(root, 'data/reviews/pilot.overlays.json'), 'utf8');
    await writeFile(rawPath, raw + ' tampered fixture');
    await expect(run('import', root)).rejects.toThrow('checksum mismatch');
    expect(await readOutput()).toBe(output);
    expect(await readFile(receiptPath, 'utf8')).toBe(receiptText);
    expect(await readFile(join(root, 'data/reviews/pilot.overlays.json'), 'utf8')).toBe(reviews);
  });
  it('does not overwrite a corrupt content-addressed cache during refresh', async () => {
    const receiptPath = join(root, 'data/import/pilot.receipt.json');
    const receiptText = await readFile(receiptPath, 'utf8');
    const receipt = JSON.parse(receiptText);
    const rawPath = join(root, `data/raw/ygoprodeck/${receipt.sha256}.json`);
    const original = await readFile(rawPath, 'utf8');
    const output = await readOutput();
    await writeFile(rawPath, 'corrupt fixture');
    vi.stubGlobal('fetch', vi.fn(async () => new Response(original, { status: 200 })));
    await expect(run('fetch', root)).rejects.toThrow('refusing overwrite');
    expect(await readFile(rawPath, 'utf8')).toBe('corrupt fixture');
    expect(await readFile(receiptPath, 'utf8')).toBe(receiptText);
    expect(await readOutput()).toBe(output);
  });
});
